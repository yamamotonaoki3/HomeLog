async function checkForm(page: Page, modal: Locator) {
  await expect(modal.getByLabel('日時', { exact: true })).toBeFocused()
  for (const input of await modal.locator('input:not([type=checkbox]):not([type=radio]):visible, select:visible, textarea:visible').all()) {
    expect(await input.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16)
  }
  await expectActionTargets44(modal)
  for (const label of await modal.locator('label:has(input[type=checkbox]):visible, label:has(input[type=radio]):visible').all()) expect((await label.boundingBox())!.height, 'checkbox/radio label: ' + await label.innerText()).toBeGreaterThanOrEqual(44)
  const count = await modal.locator('button,input,select,textarea,a[href],[tabindex]').evaluateAll(elements => elements.filter(el => (el as HTMLElement).tabIndex >= 0 && !el.matches(':disabled,input[type="hidden"]') && el.getClientRects().length > 0).length)
  for (const key of ['Tab', 'Shift+Tab']) {
    for (let index = 0; index < count; index++) {
      await page.keyboard.press(key)
      expect(await modal.evaluate(el => el.contains(document.activeElement))).toBe(true)
      const rect = await page.evaluate(() => { const box = document.activeElement!.getBoundingClientRect(); return { top: box.top, bottom: box.bottom } })
      expect(rect.top).toBeGreaterThanOrEqual(0)
      expect(rect.bottom).toBeLessThanOrEqual(page.viewportSize()!.height)
    }
    await expect(modal.getByLabel('日時', { exact: true })).toBeFocused()
  }
}
async function checkFilters(panel: Locator) {
  await expectActionTargets44(panel)
  for (const control of await panel.locator('input:visible, select:visible').all()) {
    const measured = await control.evaluate(el => ({ name: el.getAttribute('aria-label') ?? el.id, font: parseFloat(getComputedStyle(el).fontSize), height: el.getBoundingClientRect().height }))
    expect(measured.font, measured.name + ' font').toBeGreaterThanOrEqual(16)
    expect(measured.height, measured.name + ' hitbox').toBeGreaterThanOrEqual(44)
  }
}
async function shot(page: Page, width: number, label: string) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  if (process.env.KAKEIBO_SCREENSHOT_DIR) {
    await mkdir(process.env.KAKEIBO_SCREENSHOT_DIR, { recursive: true })
    await page.screenshot({ path: join(process.env.KAKEIBO_SCREENSHOT_DIR, label + '-' + width + '.png'), fullPage: true })
  }
}

