import { expect, test } from './console-guard'
import { newUser } from './support/test-data'
import { randomUUID } from 'node:crypto'
import { login, openAccountMenu, setupUserWithHousehold } from './support/flows'
import { expectNoHorizontalOverflow, readMeals, readStocks, seedOriginal, seedLinkedStock, menuHeaders } from './support/menu-inventory'

for (const width of [1280, 390, 320]) {
  test(`在庫に新規料理2件と既存レシピを登録し数量を保持する ${width}px`, async ({ page, consoleGuard }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    consoleGuard.watch(page)
    await setupUserWithHousehold(page, `menu_ui_${width}`)
    const originalTitle = '[E2E_TEST] 登録済みの料理'
    const recipeId = await seedOriginal(page, originalTitle)
    const stockName = '[E2E_TEST] 鶏肉' + '長い在庫名'.repeat(6)
    const first = '[E2E_TEST] 鶏ハム' + '長い料理名'.repeat(8)
    const second = '[E2E_TEST] 照り焼き'
    await page.goto('/zaiko')
    await page.getByRole('button', { name: '在庫を登録', exact: true }).click()
    await page.getByLabel('品名', { exact: true }).fill(stockName)
    await expect(page.getByLabel('品名', { exact: true })).toHaveValue(stockName)
    await page.getByLabel('在庫個数', { exact: true }).fill('3')
    await page.getByRole('checkbox', { name: 'レシピも登録する', exact: true }).check()
    await expect(page.getByRole('switch', { name: '毎日の自動消費', exact: true })).toBeDisabled()
    for (const title of [first, second]) {
      await page.getByLabel('新しい料理名', { exact: true }).fill(title)
      await page.getByRole('button', { name: '料理を追加', exact: true }).click()
      await expect(page.getByLabel(title + 'の使用数', { exact: true })).toHaveValue('1')
    }
    await page.getByLabel(first + 'の使用数', { exact: true }).fill('0.5')
    await page.getByRole('checkbox', { name: second + 'を翌週へ持ち越す', exact: true }).check()
    await page.getByRole('radio', { name: '登録済みレシピから選ぶ', exact: true }).check()
    await page.getByLabel('レシピを検索', { exact: true }).fill('登録済み')
    await page.getByRole('checkbox', { name: originalTitle, exact: true }).check()
    await page.getByRole('button', { name: '選んだレシピを追加', exact: true }).click()
    await expect(page.getByLabel(originalTitle + 'の使用数', { exact: true })).toHaveValue('1')
    await expectNoHorizontalOverflow(page)
    expect(await page.getByLabel(first + 'の使用数', { exact: true }).evaluate(input => parseFloat(getComputedStyle(input).fontSize))).toBeGreaterThanOrEqual(16)
    expect(await page.getByLabel(first + 'の使用数', { exact: true }).evaluate(input => input.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
    await page.screenshot({ path: testInfo.outputPath('menu-registration.png'), fullPage: true })
    await page.getByLabel(originalTitle + 'の使用数', { exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath('menu-selected-drafts.png'), fullPage: true })
    const createdResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/inventory-items' && response.request().method() === 'POST')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    const response = await createdResponse
    expect(response.status()).toBe(201)
    const created = await response.json()
    expect(created.quantity).toBe(3)
    const submitted = response.request().postDataJSON()
    expect(submitted.menuLinkage.menus).toEqual([
      { newRecipeTitle: first, usageQuantity: 0.5, carryEnabled: false },
      { newRecipeTitle: second, usageQuantity: 1, carryEnabled: true },
      { recipeId, usageQuantity: 1, carryEnabled: false },
    ])
    const row = page.getByTestId('inventory-panel').getByRole('button', { name: stockName + 'の詳細', exact: true })
    await expect(row).toBeVisible()
    const stock = (await readStocks(page)).find(item => item.id === created.id)
    expect(stock).toMatchObject({ quantity: 3 })
    expect(stock?.menuLinks).toHaveLength(3)
    expect(stock?.menuLinks.filter(link => link.recipeId === recipeId)).toHaveLength(1)
    const meals = (await readMeals(page)).filter(entry => entry.inventoryLinkage?.inventoryItemId === created.id)
    expect(meals).toHaveLength(3)
    expect(meals.map(entry => entry.recipeTitle).sort()).toEqual([first, second, originalTitle].sort())
    for (const meal of meals) expect(meal.inventoryLinkage).toMatchObject({ quantity: 3, mealState: 'uneaten', canConsume: true, canUndo: false })
    await page.goto('/menu')
    const mealRow = page.getByRole('list', { name: 'この週の献立' }).getByRole('listitem').filter({ hasText: second })
    await expect(mealRow.getByRole('button', { name: '食べた', exact: true })).toBeEnabled()
    await mealRow.getByRole('button', { name: '食べた', exact: true }).click()
    const consume = page.getByRole('dialog', { name: '食事を記録', exact: true })
    await expect(consume.getByRole('button', { name: 'キャンセル', exact: true })).toBeFocused()
    await expect(consume).toContainText('減らす数 1')
    await consume.getByRole('button', { name: '食べたことを記録', exact: true }).click()
    await expect(consume).toBeHidden()
    await expect(mealRow).toContainText('食事済み')
    expect((await readStocks(page)).find(item => item.id === created.id)?.quantity).toBe(2)
    await expect(mealRow.getByRole('button', { name: '取り消す', exact: true })).toBeEnabled()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath('menu-eaten.png'), fullPage: true })
    await expectNoHorizontalOverflow(page)
    await mealRow.getByRole('button', { name: '取り消す', exact: true }).click()
    const undo = page.getByRole('dialog', { name: '食事を取り消す', exact: true })
    await expect(undo).toContainText('戻す数 1')
    await undo.getByRole('button', { name: '食事を取り消して戻す', exact: true }).click()
    await expect(undo).toBeHidden()
    await expect(mealRow.getByRole('button', { name: '食べた', exact: true })).toBeEnabled()
    expect((await readStocks(page)).find(item => item.id === created.id)?.quantity).toBe(3)
    expect((await readMeals(page)).filter(entry => entry.inventoryLinkage?.inventoryItemId === created.id)).toHaveLength(3)
    await expectNoHorizontalOverflow(page)
  })
}

test('在庫0で持ち越しが停止し、補充後の明示再ONでも食済を復活させない', async ({ page, consoleGuard }) => {
  consoleGuard.watch(page)
  await setupUserWithHousehold(page, 'menu_zero_ui')
  const sharedRecipe = await seedOriginal(page, '[E2E_TEST] 同じ原本の料理')
  const stock = await seedLinkedStock(page, '[E2E_TEST] 最後の一食', 1, sharedRecipe)
  const otherStock = await seedLinkedStock(page, '[E2E_TEST] 別の在庫', 4, sharedRecipe)
  await page.goto('/menu')
  const row = page.getByRole('list', { name: 'この週の献立' }).getByRole('listitem').filter({ hasText: stock.name })
  const carry = row.getByRole('checkbox', { name: '来週へ持ち越す', exact: true })
  await expect(carry).toBeChecked()
  await row.getByRole('button', { name: '食べた', exact: true }).click()
  await page.getByRole('dialog', { name: '食事を記録', exact: true }).getByRole('button', { name: '食べたことを記録', exact: true }).click()
  await expect(row).toContainText('食事済み')
  await expect(carry).not.toBeChecked()
  await expect(carry).toBeDisabled()
  await expect(row).toContainText('在庫を補充してから再開してください')
  expect((await readStocks(page)).find(item => item.id === stock.id)?.quantity).toBe(0)
  expect((await readStocks(page)).find(item => item.id === otherStock.id)?.quantity).toBe(4)
  expect((await readMeals(page)).find(entry => entry.inventoryLinkage?.inventoryItemId === otherStock.id)?.inventoryLinkage?.mealState).toBe('uneaten')
  const refill = await page.request.patch(`/api/inventory-items/${stock.id}/quantity`, { headers: await menuHeaders(page), data: { delta: 1 } })
  expect(refill.status()).toBe(200)
  await page.reload()
  await expect(carry).not.toBeChecked()
  await expect(carry).toBeEnabled()
  const patchedLink = page.waitForResponse(response => new URL(response.url()).pathname === '/api/inventory-menu-links/' + stock.menuLinks[0].id && response.request().method() === 'PATCH')
  await carry.click()
  const linkResponse = await patchedLink
  expect(linkResponse.status()).toBe(200)
  expect(linkResponse.request().postDataJSON()).toMatchObject({ usageQuantity: 1, enabled: true, carryEnabled: true })
  expect(await linkResponse.json()).toMatchObject({ carryEnabled: true })
  await expect(carry).toBeChecked()
  await expect(row.getByRole('button', { name: '取り消す', exact: true })).toBeEnabled()
  await expect(row.getByRole('button', { name: '食べた', exact: true })).toHaveCount(0)
  const after = (await readStocks(page)).find(item => item.id === stock.id)!
  expect(after).toMatchObject({ quantity: 1 })
  expect(after.menuLinks[0].carryEnabled).toBe(true)
  expect((await readMeals(page)).filter(entry => entry.inventoryLinkage?.inventoryItemId === stock.id)).toHaveLength(1)
})

test('実食保存後の応答喪失をreload・別世帯login後も同一要求で一度だけ回復する', async ({ page, consoleGuard }) => {
  consoleGuard.watch(page)
  const actor = await setupUserWithHousehold(page, 'menu_unknown_a')
  const stock = await seedLinkedStock(page, '[E2E_TEST] 回復する一食')
  const meal = (await readMeals(page)).find(entry => entry.inventoryLinkage?.inventoryItemId === stock.id)!
  const stranger = newUser('menu_unknown_b')
  expect((await page.request.post('/api/auth/register', { data: stranger })).status()).toBe(201)
  const authB = await page.request.post('/api/auth/login', { data: { email: stranger.email, password: stranger.password } })
  expect(authB.status()).toBe(200)
  const headersB = { Authorization: `Bearer ${(await authB.json()).accessToken}` }
  expect((await page.request.post('/api/households', { headers: headersB, data: { name: '[E2E_TEST] 別世帯' } })).status()).toBe(201)
  const path = `/api/menu-entries/${meal.id}/consume`
  const sent: { requestId: string; expectedRevision: number }[] = []
  page.on('request', request => { if (new URL(request.url()).pathname === path && request.method() === 'POST') sent.push(request.postDataJSON()) })
  consoleGuard.allow({ url: new RegExp(path + '$'), message: 'Failed to load resource: the server responded with a status of 503 (Service Unavailable)' })
  await page.route('**' + path, async route => {
    const response = await route.fetch()
    expect(response.status()).toBe(200)
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'EXTERNAL_SERVICE_ERROR', message: '[E2E_TEST] 保存後の応答喪失', details: [] }) })
  })
  await page.goto('/menu')
  const row = page.getByRole('list', { name: 'この週の献立' }).getByRole('listitem').filter({ hasText: stock.name + 'の料理' })
  await row.getByRole('button', { name: '食べた', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '食事を記録', exact: true })
  await dialog.getByRole('button', { name: '食べたことを記録', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByRole('button', { name: 'キャンセル', exact: true }).click()
  const recover = page.getByRole('button', { name: '前回の結果を確認', exact: true })
  await expect(recover).toBeEnabled()
  expect(sent).toHaveLength(1)
  expect((await readStocks(page)).find(item => item.id === stock.id)?.quantity).toBe(2)
  await page.unroute('**' + path)
  await page.reload()
  await expect(recover).toBeEnabled()
  expect(sent).toHaveLength(1)
  await (await openAccountMenu(page)).getByRole('button', { name: 'ログアウト', exact: true }).click()
  await login(page, stranger)
  await expect(page).not.toHaveURL(/\/login$/)
  await page.goto('/menu')
  await expect(page.getByRole('list', { name: 'この週の献立' })).toBeVisible()
  await expect(recover).toHaveCount(0)
  await expect(page.getByText(stock.name + 'の料理', { exact: true })).toHaveCount(0)
  expect(await readStocks(page)).toEqual([])
  expect(await readMeals(page)).toEqual([])
  expect(sent).toHaveLength(1)
  expect((await page.request.post(path, { headers: headersB, data: { requestId: randomUUID(), expectedRevision: 1 } })).status()).toBe(404)
  await (await openAccountMenu(page)).getByRole('button', { name: 'ログアウト', exact: true }).click()
  await login(page, actor)
  await expect(page).not.toHaveURL(/\/login$/)
  await page.goto('/menu')
  await expect(recover).toBeEnabled()
  await recover.click()
  await expect(recover).toHaveCount(0)
  await expect(row.getByRole('button', { name: '取り消す', exact: true })).toBeEnabled()
  expect(sent).toHaveLength(2)
  expect(sent[1]).toEqual(sent[0])
  expect((await readStocks(page)).find(item => item.id === stock.id)?.quantity).toBe(2)
  expect((await readMeals(page)).find(entry => entry.id === meal.id)?.inventoryLinkage).toMatchObject({ mealState: 'eaten', mealRevision: 1 })
})
