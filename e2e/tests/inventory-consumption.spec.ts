import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { expectActionTargets44 } from './support/list-row'
import { test, expect } from './console-guard'
import { setupConsumptionUser } from './support/inventory-consumption'
import { openInventoryDetails } from './support/flows'

for (const width of [1280, 390, 320]) {
  test('日次消費の登録・オンオフ・詳細・保存到達 ' + width + 'px (#329/#420)', async ({ page, consoleGuard }) => {
    await page.setViewportSize({ width, height: 640 })
    consoleGuard.watch(page)
    await setupConsumptionUser(page, 'consumption_ui_' + width)
    await page.goto('/zaiko')
    const name = '[E2E_TEST] testuser_日次消費'
    const origin = page.getByRole('button', { name: '在庫を登録', exact: true })
    await origin.click()
    const form = page.getByRole('dialog', { name: '在庫を登録' })
    await form.getByLabel('品名', { exact: true }).fill(name)
    const toggle = form.getByRole('switch', { name: '自動消費' })
    const consumption = form.getByLabel('1日の消費量（任意）')
    await expect(toggle).toHaveAttribute('aria-checked', 'false')
    await expect(toggle).toBeEnabled()
    await expect(consumption).toBeHidden()
    await toggle.click()
    await expect(consumption).toBeVisible()
    let writes = 0
    page.on('request', request => { if (['POST', 'PATCH'].includes(request.method()) && /\/api\/inventory-items(?:\/\d+)?$/.test(new URL(request.url()).pathname)) writes++ })
    await form.getByRole('button', { name: '保存', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('消費量')
    expect(writes).toBe(0)
    await consumption.fill('0.2')
    await expect(toggle).toHaveAttribute('aria-checked', 'true')
    await toggle.focus()
    await page.keyboard.press('Space')
    await expect(toggle).toHaveAttribute('aria-checked', 'false')
    await expect(consumption).toBeHidden()
    await page.keyboard.press('Space')
    await expect(toggle).toHaveAttribute('aria-checked', 'true')
    await expect(consumption).toHaveValue('0.2')
    await expectActionTargets44(form)
    if (process.env.INVENTORY_CONSUMPTION_SCREENSHOT_DIR) {
      await mkdir(process.env.INVENTORY_CONSUMPTION_SCREENSHOT_DIR, { recursive: true })
      await consumption.scrollIntoViewIfNeeded()
      await page.screenshot({ path: join(process.env.INVENTORY_CONSUMPTION_SCREENSHOT_DIR, 'inventory-consumption-' + width + '.png'), fullPage: true })
    }
    expect(await form.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(form.getByLabel('カテゴリー', { exact: true })).not.toHaveValue('')
    const categoryId = Number(await form.getByLabel('カテゴリー', { exact: true }).inputValue())
    const initialBody = { dailyConsumption: 0.2, autoConsumptionEnabled: true, name, categoryId, storeId: null, threshold: 0.5, price: null, quantity: 1 }
    const post = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/inventory-items')
    await form.getByRole('button', { name: '保存', exact: true }).click()
    expect((await post).postDataJSON()).toEqual(initialBody)
    await expect(form).toBeHidden()
    const row = page.getByRole('button', { name: name + 'の詳細', exact: true })
    await expect(row.locator('.inventory-list-quantity')).toHaveText('1.0')
    await expect(origin).toBeFocused()
    const detailTrigger = page.getByRole('button', { name: name + 'の詳細設定', exact: true })
    await openInventoryDetails(page, row)
    const edit = page.getByRole('dialog', { name: '在庫詳細・編集' })
    const editToggle = edit.getByRole('switch', { name: '自動消費' })
    const editConsumption = edit.getByLabel('1日の消費量（任意）')
    await expect(editToggle).toHaveAttribute('aria-checked', 'true')
    await expect(editConsumption).toHaveValue('0.2')
    const beforeCancel = writes
    await editConsumption.fill('0.3')
    await editToggle.click()
    await page.keyboard.press('Escape')
    await expect(detailTrigger).toBeFocused()
    expect(writes).toBe(beforeCancel)
    await openInventoryDetails(page, row)
    await expect(editToggle).toHaveAttribute('aria-checked', 'true')
    await expect(editConsumption).toHaveValue('0.2')
    const saveSettings = async (dailyConsumption: number | null, autoConsumptionEnabled: boolean) => {
      const patch = page.waitForRequest(request => request.method() === 'PATCH' && /\/api\/inventory-items\/\d+$/.test(new URL(request.url()).pathname))
      await edit.getByRole('button', { name: '保存', exact: true }).click()
      expect((await patch).postDataJSON()).toEqual({ dailyConsumption, autoConsumptionEnabled, name, categoryId, storeId: null, threshold: 0.5, price: null })
      await expect(edit).toBeHidden()
    }
    await editToggle.click()
    await expect(editConsumption).toBeHidden()
    await saveSettings(0.2, false)
    await openInventoryDetails(page, row)
    await expect(editToggle).toHaveAttribute('aria-checked', 'false')
    await expect(editConsumption).toBeHidden()
    await expect(edit.locator('.qty-value')).toHaveText('1.0')
    await editToggle.click()
    await expect(editConsumption).toHaveValue('0.2')
    await saveSettings(0.2, true)
    await openInventoryDetails(page, row)
    await expect(editToggle).toHaveAttribute('aria-checked', 'true')
    await expect(edit.locator('.qty-value')).toHaveText('1.0')
    await editConsumption.fill('')
    const beforeInvalid = writes
    await edit.getByRole('button', { name: '保存', exact: true }).click()
    await expect(edit.getByRole('alert')).toContainText('消費量')
    expect(writes).toBe(beforeInvalid)
    await expect(editToggle).toBeEnabled()
    await editToggle.click()
    await saveSettings(null, false)
    await openInventoryDetails(page, row)
    await expect(editToggle).toHaveAttribute('aria-checked', 'false')
    await expect(editConsumption).toBeHidden()
    await expect(editToggle).toBeEnabled()
    await editToggle.click()
    await expect(editConsumption).toBeVisible()
    await expect(editConsumption).toHaveValue('')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(detailTrigger).toBeFocused()
    const token = await page.evaluate(() => localStorage.getItem('homelog.accessToken'))
    const response = await page.request.get('/api/inventory-items', { headers: { Authorization: 'Bearer ' + token } })
    expect(response.ok()).toBe(true)
    expect(await response.json()).toEqual([expect.objectContaining({ name, quantity: 1, dailyConsumption: null, autoConsumptionEnabled: false })])
    for (const invalid of ['0', '0.01']) {
      await openInventoryDetails(page, row)
      await expect(editToggle).toHaveAttribute('aria-checked', 'false')
      await editToggle.click()
      await editConsumption.fill(invalid)
      await editToggle.click()
      await expect(editConsumption).toBeHidden()
      const beforeCorrection = writes
      await edit.getByRole('button', { name: '保存', exact: true }).click()
      await expect(edit.getByRole('alert')).toContainText('消費量')
      expect(writes).toBe(beforeCorrection)
      await expect(editToggle).toHaveAttribute('aria-checked', 'false')
      await expect(editConsumption).toBeVisible()
      await expect(editConsumption).toHaveValue(invalid)
      await expect(editConsumption).toHaveAttribute('aria-invalid', 'true')
      await expect(editConsumption).toHaveAccessibleDescription(/1日の消費量/)
      if (process.env.INVENTORY_CONSUMPTION_SCREENSHOT_DIR) {
        await edit.getByRole('alert').scrollIntoViewIfNeeded()
        await page.screenshot({ path: join(process.env.INVENTORY_CONSUMPTION_SCREENSHOT_DIR, 'inventory-consumption-correction-' + width + '.png') })
      }
      await editConsumption.fill('1')
      await expect(editConsumption).toBeVisible()
      await expect(editConsumption).toHaveValue('1')
      await editConsumption.press('End')
      await editConsumption.pressSequentially('.5')
      await expect(editConsumption).toBeVisible()
      await expect(editConsumption).toHaveValue('1.5')
      await expect(editToggle).toHaveAttribute('aria-checked', 'false')
      await saveSettings(1.5, false)
      await expect(detailTrigger).toBeFocused()
    }
    const correctedResponse = await page.request.get('/api/inventory-items', { headers: { Authorization: 'Bearer ' + token } })
    expect(correctedResponse.ok()).toBe(true)
    expect(await correctedResponse.json()).toEqual([expect.objectContaining({ name, quantity: 1, dailyConsumption: 1.5, autoConsumptionEnabled: false })])
  })
}
