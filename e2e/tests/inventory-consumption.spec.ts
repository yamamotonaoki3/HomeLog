import { test, expect } from './console-guard'
import { setupConsumptionUser } from './support/inventory-consumption'

for (const width of [1280, 390, 320]) {
  test(`日次消費の登録・オンオフ・詳細・保存到達 ${width}px (#329)`, async ({ page, consoleGuard }) => {
    await page.setViewportSize({ width, height: 640 })
    consoleGuard.watch(page)
    await setupConsumptionUser(page, `consumption_ui_${width}`)
    await page.goto('/zaiko')
    const name = '[E2E_TEST] testuser_日次消費'
    const origin = page.getByRole('button', { name: '在庫を登録', exact: true })
    await origin.click()
    const form = page.getByRole('dialog', { name: '在庫を登録' })
    await form.getByLabel('品名', { exact: true }).fill(name)
    await form.getByLabel('1日の消費量（任意）').fill('0.2')
    const toggle = form.getByRole('switch', { name: '自動消費' })
    await expect(toggle).toHaveAttribute('aria-checked', 'true')
    await toggle.focus()
    await page.keyboard.press('Space')
    await expect(toggle).toHaveAttribute('aria-checked', 'false')
    await page.keyboard.press('Space')
    await expect(toggle).toHaveAttribute('aria-checked', 'true')
    expect(await form.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await form.getByRole('button', { name: '保存', exact: true }).click()
    await expect(form).toBeHidden()
    const row = page.getByRole('button', { name: `${name}の詳細`, exact: true })
    await expect(row.locator('.inventory-list-quantity')).toHaveText('1.0')
    await expect(origin).toBeFocused()
    await row.click()
    const detail = page.getByRole('dialog', { name: '在庫詳細・編集' })
    await expect(detail.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
    const edit = page.getByRole('dialog', { name: '在庫詳細・編集' })
    await expect(edit.getByLabel('1日の消費量（任意）')).toHaveValue('0.2')
    await edit.getByRole('switch', { name: '自動消費' }).click()
    await expect(edit.getByLabel('1日の消費量（任意）')).toHaveValue('0.2')
    await edit.getByRole('button', { name: '保存', exact: true }).click()
    await expect(edit).toBeHidden()
    await row.click()
    await expect(detail.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
    await expect(detail.locator('.qty-value')).toHaveText('1.0')
    await page.keyboard.press('Escape')
    await expect(row).toBeFocused()
    await row.click()
    await edit.getByRole('switch', { name: '自動消費' }).click()
    await edit.getByRole('button', { name: '保存', exact: true }).click()
    await expect(edit).toBeHidden()
    await row.click()
    await expect(detail.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
    await expect(detail.locator('.qty-value')).toHaveText('1.0')
    await edit.getByLabel('1日の消費量（任意）').fill('')
    await expect(edit.getByRole('switch')).toBeDisabled()
    await edit.getByRole('button', { name: '保存', exact: true }).click()
    await expect(edit).toBeHidden()
    await row.click()
    await expect(edit.getByLabel('1日の消費量（任意）')).toHaveValue('')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(row).toBeFocused()
  })
}
