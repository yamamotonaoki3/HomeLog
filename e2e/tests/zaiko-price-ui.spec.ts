import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { test, expect } from './console-guard'
import { setupUserWithHousehold } from './support/flows'

for (const width of [1280, 390, 320]) {
  test(`値段登録・編集・手動追加と画面幅 ${width}px`, async ({ page, consoleGuard }) => {
    await page.setViewportSize({ width, height: 900 })
    consoleGuard.watch(page)
    await setupUserWithHousehold(page, `price_ui_${width}`)
    await page.goto('/zaiko')
    const shots = process.env.ZAIKO_SCREENSHOT_DIR
    const screenshot = async (name: string) => {
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
      if (shots) { await mkdir(shots, { recursive: true }); await page.screenshot({ path: join(shots, `${name}-${width}.png`), fullPage: true }) }
    }
    const name = '[E2E_TEST]' + '長い品名'.repeat(10)
    await page.getByRole('button', { name: '在庫を登録' }).click()
    await page.getByLabel('品名', { exact: true }).fill(name)
    await page.getByRole('button', { name: '＋店を登録' }).click()
    await page.getByLabel('店名', { exact: true }).fill('[E2E_TEST]' + '長い店名'.repeat(10))
    await page.getByRole('button', { name: '店を追加', exact: true }).click()
    await page.getByLabel('在庫個数', { exact: true }).fill('0')
    await page.getByLabel('買い物リスト追加閾値').fill('0.5')
    await page.getByLabel('値段（円・任意）').fill('9999999999')
    await screenshot('register')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    const inventory = page.getByTestId('inventory-panel')
    const row = inventory.getByRole('button', { name: `${name}の詳細`, exact: true })
    await row.click()
    const detail = page.getByRole('dialog', { name: '在庫詳細' })
    const price = detail.locator('dd').last()
    await expect(price).toHaveText('9,999,999,999円')
    expect(await price.evaluate((cell) => cell.scrollWidth <= cell.clientWidth)).toBe(true)
    await price.scrollIntoViewIfNeeded()
    await screenshot('inventory-upper')
    await detail.getByRole('button', { name: `${name}を編集`, exact: true }).click()
    await expect(page.getByLabel('値段（円・任意）')).toHaveValue('9999999999')
    await expect(page.getByLabel('在庫個数', { exact: true })).toBeDisabled()
    await page.getByLabel('値段（円・任意）').fill('1280')
    await screenshot('edit')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(price).toHaveText('1,280円')
    await page.reload()
    await row.click()
    await expect(price).toHaveText('1,280円')
    await price.scrollIntoViewIfNeeded()
    await screenshot('inventory')
    await detail.getByRole('button', { name: '閉じる' }).click()
    const tabs = page.getByRole('navigation', { name: '在庫管理関連機能' })
    await tabs.getByRole('link', { name: '買い物リスト' }).click()
    const shopping = page.getByTestId('shopping-panel')
    const shoppingRow = shopping.getByRole('button', { name: `${name}の詳細`, exact: true })
    const shoppingDetail = page.getByRole('dialog', { name: '買い物詳細' })
    const shoppingPrice = shoppingDetail.locator('dd').nth(3)
    await shoppingRow.click()
    await expect(shoppingPrice).toHaveText('1,280円')
    await shoppingDetail.getByRole('button', { name: `${name}の購入個数を増やす`, exact: true }).click()
    await shoppingDetail.getByRole('button', { name: '閉じる' }).click()
    await shopping.getByRole('button', { name: '更新', exact: true }).click()
    await expect(shoppingRow).toHaveCount(0)
    await tabs.getByRole('link', { name: '在庫一覧' }).click()
    await row.click()
    await detail.getByRole('button', { name: `${name}を減らす`, exact: true }).click()
    await expect(detail.locator('.qty-value')).toHaveText('0.0')
    await detail.getByRole('button', { name: '閉じる' }).click()
    await tabs.getByRole('link', { name: '買い物リスト' }).click()
    await shoppingRow.click()
    await expect(shoppingPrice).toHaveText('1,280円')
    await shoppingDetail.getByRole('button', { name: `${name}を削除`, exact: true }).click()
    await expect(shoppingRow).toHaveCount(0)
    await shopping.getByRole('button', { name: '品目を手動追加' }).click()
    await page.getByLabel('追加する品目').selectOption({ label: name })
    await expect(page.getByLabel('値段（円・任意）')).toHaveValue('1280')
    await page.getByLabel('値段（円・任意）').fill('980')
    await tabs.getByRole('link', { name: '在庫一覧' }).click()
    await tabs.getByRole('link', { name: '買い物リスト' }).click()
    await expect(page.getByLabel('値段（円・任意）')).toHaveValue('980')
    await expect(shopping).toBeVisible()
    await expect(page.getByLabel('値段（円・任意）')).toBeVisible()
    await screenshot('manual-add')
    await shopping.getByRole('button', { name: '追加', exact: true }).click()
    await shoppingRow.click()
    await expect(shoppingPrice).toHaveText('980円')
    await shoppingPrice.scrollIntoViewIfNeeded()
    await screenshot('shopping')
    await shoppingDetail.getByRole('button', { name: `${name}を削除`, exact: true }).click()
    await expect(shoppingRow).toHaveCount(0)
    await shopping.getByRole('button', { name: '品目を手動追加' }).click()
    await expect(page.getByLabel('追加する品目')).toHaveValue('')
    await page.getByLabel('追加する品目').selectOption({ label: name })
    await expect(page.getByLabel('値段（円・任意）')).toHaveValue('980')
    await page.getByLabel('値段（円・任意）').fill('')
    await shopping.getByRole('button', { name: '追加', exact: true }).click()
    await shoppingRow.click()
    await expect(shoppingPrice).toHaveText('980円')
    await shoppingDetail.getByRole('button', { name: '閉じる' }).click()
    await tabs.getByRole('link', { name: '在庫一覧' }).click()
    await row.click()
    await expect(price).toHaveText('980円')
    await detail.getByRole('button', { name: `${name}を編集`, exact: true }).click()
    await page.getByLabel('値段（円・任意）').fill('')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(price).toHaveText('未設定')
    await detail.getByRole('button', { name: '閉じる' }).click()
    await page.getByRole('button', { name: '在庫を登録' }).click()
    await page.getByLabel('品名', { exact: true }).fill('[E2E_TEST] 値段なし')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await inventory.getByRole('button', { name: '[E2E_TEST] 値段なしの詳細' }).click()
    await expect(price).toHaveText('未設定')
  })
}
