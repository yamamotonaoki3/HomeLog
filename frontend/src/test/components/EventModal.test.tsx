import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { apiClient } from '../../api/client'
import { EventModal } from '../../components/events/EventModal'
import type { Event } from '../../api/eventTypes'

const saved: Event = { id: 1, name: 'testuser_旅行', eventDate: '2026-09-20', isAllDay: true, startTime: null, endTime: null, recurrenceType: 'none', notifyEnabled: true, defaultAmount: 3000, showOnDashboard: false, personal: true, editable: true }
function setup(event: Event | null = saved) {
  vi.restoreAllMocks()
  const onClose = vi.fn(), onSaved = vi.fn().mockResolvedValue(undefined), onDeleted = vi.fn()
  const patch = vi.spyOn(apiClient, 'patch').mockResolvedValue({ data: event } as never)
  const post = vi.spyOn(apiClient, 'post').mockResolvedValue({ data: event } as never)
  vi.spyOn(apiClient, 'get').mockResolvedValue({ data: { total: 0 } } as never)
  render(<EventModal event={event} onClose={onClose} onSaved={onSaved} onDeleted={onDeleted} />)
  return { user: userEvent.setup(), onClose, onSaved, onDeleted, patch, post }
}

describe('イベント共通フォーム #426', () => {
  it('旧単発trueもOFF・操作不可で表示し、取消では保存しない', async () => {
    const { user, patch, post, onClose } = setup()
    expect(screen.getByLabelText('通知する')).not.toBeChecked()
    expect(screen.getByLabelText('通知する')).toBeDisabled()
    expect(screen.getByText('単発イベントは通知対象外です')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'キャンセル' }))
    expect(onClose).toHaveBeenCalledOnce()
    expect(patch).not.toHaveBeenCalled()
    expect(post).not.toHaveBeenCalled()
    expect(saved.notifyEnabled).toBe(true)
  })
  it('旧単発trueを明示保存した場合だけfalseを送る（全payload維持）', async () => {
    const { user, patch } = setup()
    await user.click(screen.getByRole('button', { name: '更新' }))
    await waitFor(() => expect(patch).toHaveBeenCalledWith('/events/1', {
      name: saved.name, eventDate: saved.eventDate, isAllDay: true, startTime: null, endTime: null,
      recurrenceType: 'none', notifyEnabled: false, defaultAmount: 3000, showOnDashboard: false, personal: true,
    }))
  })
  it.each(['daily', 'weekly', 'monthly', 'yearly'] as const)('%s→単発→繰返では通知を自動復元せず手動ONする', async recurrenceType => {
    const { user, patch } = setup({ ...saved, recurrenceType })
    expect(screen.getByLabelText('通知する')).toBeChecked()
    await user.selectOptions(screen.getByLabelText('繰り返し'), 'none')
    expect(screen.getByLabelText('通知する')).not.toBeChecked()
    expect(screen.getByLabelText('通知する')).toBeDisabled()
    await user.selectOptions(screen.getByLabelText('繰り返し'), recurrenceType)
    expect(screen.getByLabelText('通知する')).not.toBeChecked()
    expect(screen.getByLabelText('通知する')).toBeEnabled()
    await user.click(screen.getByLabelText('通知する'))
    await user.click(screen.getByRole('button', { name: '更新' }))
    await waitFor(() => expect(patch).toHaveBeenCalledWith('/events/1', expect.objectContaining({ recurrenceType, notifyEnabled: true })))
  })
  it('単発へ変更して保存すると通知falseで、他の時刻等は維持する', async () => {
    const { user, patch } = setup({ ...saved, recurrenceType: 'daily', isAllDay: false, startTime: '09:00', endTime: '10:00' })
    await user.selectOptions(screen.getByLabelText('繰り返し'), 'none')
    await user.click(screen.getByRole('button', { name: '更新' }))
    await waitFor(() => expect(patch).toHaveBeenCalledWith('/events/1', expect.objectContaining({ notifyEnabled: false, recurrenceType: 'none', startTime: '09:00', endTime: '10:00' })))
  })
  it('新規は単発・通知OFFで、権限のない削除を表示しない', async () => {
    const { user, post } = setup(null)
    expect(screen.getByLabelText('通知する')).toBeDisabled()
    expect(screen.getByLabelText('通知する')).not.toBeChecked()
    expect(screen.queryByRole('button', { name: /を削除/ })).not.toBeInTheDocument()
    await user.type(screen.getByLabelText('イベント名'), 'testuser_新規')
    await user.type(screen.getByLabelText('日付'), '2026-09-20')
    await user.click(screen.getByRole('button', { name: '登録' }))
    await waitFor(() => expect(post).toHaveBeenCalledWith('/events', expect.objectContaining({ recurrenceType: 'none', notifyEnabled: false, defaultAmount: null, showOnDashboard: true, personal: false })))
  })
  it('その他の設定だけを折りたたみ、公開範囲と通知は常時表示する', async () => {
    const { user } = setup()
    const summary = screen.getByRole('button', { name: /^その他の設定/ })
    expect(summary).toHaveAttribute('aria-expanded', 'false')
    expect(summary).toHaveTextContent('3,000円・サマリー非表示')
    expect(screen.getByRole('group', { name: '公開範囲' }).closest('.event-other-settings')).toBeNull()
    expect(screen.getByLabelText('通知する').closest('.event-other-settings')).toBeNull()
    await user.click(summary)
    await user.clear(screen.getByLabelText('デフォルト金額（任意）'))
    await user.type(screen.getByLabelText('デフォルト金額（任意）'), '4200')
    await user.click(screen.getByLabelText('トップ画面のイベント別支出サマリーに表示する'))
    await user.click(summary)
    expect(summary).toHaveTextContent('4,200円・サマリー表示')
    await user.click(summary)
    expect(screen.getByLabelText('デフォルト金額（任意）')).toHaveValue(4200)
  })
  it('時刻は日付・終日チェック後の同じ2列コンテナにあり、既存validationを維持する', async () => {
    const { user, patch } = setup()
    await user.click(screen.getByLabelText('終日'))
    const start = screen.getByLabelText('開始時刻'), end = screen.getByLabelText('終了時刻（任意）')
    expect(start.closest('.event-time-inputs')).toBe(end.closest('.event-time-inputs'))
    expect(start.closest('.event-time-inputs')).not.toBeNull()
    await user.click(screen.getByRole('button', { name: '更新' }))
    expect(screen.getByRole('alert')).toHaveTextContent('開始時刻を入力')
    await user.type(start, '10:00')
    await user.type(end, '09:00')
    await user.click(screen.getByRole('button', { name: '更新' }))
    expect(screen.getByRole('alert')).toHaveTextContent('終了時刻は開始時刻より後')
    expect(patch).not.toHaveBeenCalled()
  })
  it('上部ゴミ箱から同dialogで確認し取消後はdraftと開閉状態・focusを維持する', async () => {
    const { user } = setup()
    const dialog = screen.getByRole('dialog'), trash = screen.getByRole('button', { name: saved.name + 'を削除' })
    expect(trash.closest('.event-editor-header')).not.toBeNull()
    expect(within(dialog.querySelector<HTMLElement>('.event-editor-actions')!).queryByRole('button', { name: /削除/ })).not.toBeInTheDocument()
    await user.clear(screen.getByLabelText('イベント名'))
    await user.type(screen.getByLabelText('イベント名'), 'testuser_下書き')
    const summary = screen.getByRole('button', { name: /^その他の設定/ })
    await user.click(summary)
    await user.click(trash)
    expect(screen.getAllByRole('dialog')).toEqual([dialog])
    expect(screen.getByRole('button', { name: '削除をやめる' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: '削除をやめる' }))
    expect(screen.getByLabelText('イベント名')).toHaveValue('testuser_下書き')
    expect(summary).toHaveAttribute('aria-expanded', 'true')
    await waitFor(() => expect(trash).toHaveFocus())
  })
  it('送信中は多重保存と閉鎖を防ぎ失敗後draftを保持する', async () => {
    const { user, patch, onClose } = setup()
    let reject!: (reason: Error) => void
    patch.mockImplementationOnce(() => new Promise((_, fail) => { reject = fail }))
    await user.click(screen.getByRole('button', { name: '更新' }))
    expect(screen.getByRole('button', { name: 'キャンセル' })).toBeDisabled()
    expect(screen.getByRole('button', { name: saved.name + 'を削除' })).toBeDisabled()
    await user.keyboard('{Escape}')
    expect(onClose).not.toHaveBeenCalled()
    await act(async () => reject(new Error('testuser_save_failed')))
    expect(await screen.findByRole('alert')).toBeInTheDocument()
    expect(screen.getByLabelText('イベント名')).toHaveValue(saved.name)
    expect(screen.getByRole('button', { name: '更新' })).toBeEnabled()
    expect(patch).toHaveBeenCalledOnce()
  })
})

it('詳細設定はキーボードで開閉でき、hidden入力をTab巡回しない', async () => {
  const { user } = setup()
  const toggle = screen.getByRole('button', { name: /^その他の設定/ })
  toggle.focus()
  await user.keyboard(' ')
  expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await user.tab()
  expect(screen.getByLabelText('デフォルト金額（任意）')).toHaveFocus()
  toggle.focus()
  await user.keyboard('{Enter}')
  expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await user.tab()
  expect(screen.getByLabelText('集計対象期間')).toHaveFocus()
})
it.each(['0', '-1', '1.5'])('その他設定を閉じても不正金額%sは保存されない', async amount => {
  const { user, patch } = setup()
  const toggle = screen.getByRole('button', { name: /^その他の設定/ })
  await user.click(toggle)
  await user.clear(screen.getByLabelText('デフォルト金額（任意）'))
  await user.type(screen.getByLabelText('デフォルト金額（任意）'), amount)
  await user.click(toggle)
  await user.click(screen.getByRole('button', { name: '更新' }))
  expect(screen.getByRole('alert')).toHaveTextContent('デフォルト金額は1以上の整数')
  expect(patch).not.toHaveBeenCalled()
})
it('空金額・終了なしを保存し、隠した入力値を勝手に初期化しない', async () => {
  const { user, patch } = setup({ ...saved, isAllDay: false, startTime: '09:00', endTime: null })
  const toggle = screen.getByRole('button', { name: /^その他の設定/ })
  await user.click(toggle)
  await user.clear(screen.getByLabelText('デフォルト金額（任意）'))
  await user.click(toggle)
  expect(toggle).toHaveTextContent('金額未設定・サマリー非表示')
  await user.click(screen.getByRole('button', { name: '更新' }))
  await waitFor(() => expect(patch).toHaveBeenCalledWith('/events/1', expect.objectContaining({ defaultAmount: null, startTime: '09:00', endTime: null })))
})
it('削除pendingは二重送信/閉鎖を防ぎ、失敗・取消・再試行でもdraftを保つ', async () => {
  const { user, onClose, onDeleted } = setup()
  let reject!: (reason: Error) => void
  const remove = vi.spyOn(apiClient, 'delete').mockImplementationOnce(() => new Promise((_, fail) => { reject = fail })).mockResolvedValue({} as never)
  await user.clear(screen.getByLabelText('イベント名'))
  await user.type(screen.getByLabelText('イベント名'), 'testuser_削除前')
  const trash = screen.getByRole('button', { name: saved.name + 'を削除' })
  await user.click(trash)
  await user.click(screen.getByRole('button', { name: '削除する' }))
  expect(screen.getByRole('button', { name: '削除する' })).toBeDisabled()
  expect(screen.getByRole('button', { name: '削除をやめる' })).toBeDisabled()
  await user.keyboard('{Escape}')
  expect(onClose).not.toHaveBeenCalled()
  await act(async () => reject(new Error('testuser_delete_failed')))
  expect(await screen.findByRole('alert')).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: '削除をやめる' }))
  expect(screen.getByLabelText('イベント名')).toHaveValue('testuser_削除前')
  expect(trash).toHaveFocus()
  await user.click(trash)
  await user.click(screen.getByRole('button', { name: '削除する' }))
  await waitFor(() => expect(onDeleted).toHaveBeenCalledOnce())
  expect(remove).toHaveBeenCalledTimes(2)
})
